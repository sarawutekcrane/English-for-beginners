"""Expands every pattern's wordOrderQuestions to 20 entries (from ~10-12).

Each new question follows the exact existing schema (id, promptThai, chunks
with text/phonetic[/isDistractor], correctOrder, phonetic, thai,
explanation) and matches the distractor-density convention already
established per pattern (verified by inspecting every existing question's
chunks before writing any new ones):
  - present-simple, past-simple, present-continuous, comparatives: every
    question gets the full applicable wrong-form set (100% in existing data).
  - have-has, there-is-are, can-could-ability: distractors on most but not
    all questions (mixed statement/negative/question forms).
  - going-to-future, will-future, first-conditional: distractors sparse,
    used only where the existing data used them (e.g. am/is/are only on
    "will be" sentences).
  - zero-conditional: no distractor mechanic at all, matching its existing
    10/10 distractor-free convention.

New sentences reuse verbs.json/adjectives.json forms+phonetics for every
verb/adjective drilled (to keep distractor chunks accurate), and introduce
fresh subjects/objects/contexts not used in the existing ~10-12 questions
per pattern so the practice set doesn't feel repetitive.
"""
import json

PATH = "src/data/sentencePatterns.json"

with open(PATH, encoding="utf-8") as f:
    patterns = json.load(f)

by_id = {p["id"]: p for p in patterns}


def chunk(text, phonetic, distractor=False):
    c = {"text": text, "phonetic": phonetic}
    if distractor:
        c["isDistractor"] = True
    return c


def build(qid, prompt_thai, correct_chunks, distractor_chunks, thai, explanation):
    """correct_chunks: list of (text, phonetic) in correct order.
    distractor_chunks: list of (text, phonetic) marked isDistractor."""
    chunks = [chunk(t, p) for t, p in correct_chunks] + [
        chunk(t, p, distractor=True) for t, p in distractor_chunks
    ]
    return {
        "id": qid,
        "promptThai": prompt_thai,
        "chunks": chunks,
        "correctOrder": [t for t, _ in correct_chunks],
        "phonetic": " ".join(p for _, p in correct_chunks),
        "thai": thai,
        "explanation": explanation,
    }


